# 后者是「被截断的需求」（censored demand），直接当 0 训练会让模型系统性低估，
# 低估又导致下一轮备货更保守，形成缺货循环。下面三条规则只使用当日及以前的信息，
# 不引入未来数据，因此可以安全地用于训练输入。

# 促销判定：当日价格低于「过去 182 天常态价」该比例以上，计为促销日。
# 窗口取 182 天而不是 28 天：这批 SKU 的价格档位中位数只有 2 档（常态价 + 促销价），
# 用 28 天窗口时，一旦促销持续两周以上，窗口内中位数本身就被促销价拉低，促销识别会失效。
PROMO_PRICE_DROP  = 0.02
PROMO_PRICE_WIN   = 182
