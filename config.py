# 疑似缺货判定（两条规则，全部只用当日及以前的信息）
#   规则 1：促销日 + 零销量 —— 打折还没卖掉，几乎只可能是没货
#   规则 2：零销量且该序列平时基本天天有销量（过去 28 天零销占比低于阈值）
# 曾试过「连续零销 >= 3 天」，被数据否决：这条规则命中的日子其后 7 天销量只恢复到
# 常态水平的 28%（未判缺货的零销日是 70%），更像 SKU 停售而非断货。检验见 README §3.1。
